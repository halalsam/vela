import { AwsClient } from 'aws4fetch';
import { mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { dirname, resolve, sep } from 'node:path';
import type { Env } from '../../env';
import type { Logger } from '../../logger';

export type StorageDriver = 's3' | 'disk';
export type StoredFile = { key: string; url: string; driver: StorageDriver };

export type Storage = {
  /** Where new uploads go first. */
  primary: StorageDriver;
  put(key: string, body: Uint8Array, contentType: string): Promise<StoredFile>;
  remove(key: string, driver: StorageDriver): Promise<void>;
  /** Reads a file saved on this server's disk, or null. */
  readDisk(key: string): Promise<Uint8Array | null>;
};

const CACHE = 'public, max-age=31536000, immutable';

function diskStore(env: Env) {
  const root = resolve(env.UPLOAD_DIR);
  // Keys are generated by the server, but check anyway that nothing escapes the upload folder.
  const pathOf = (key: string) => {
    const full = resolve(root, key);
    if (!full.startsWith(root + sep)) throw new Error('Upload key outside the upload folder');
    return full;
  };
  return {
    async put(key: string, body: Uint8Array): Promise<StoredFile> {
      const full = pathOf(key);
      await mkdir(dirname(full), { recursive: true });
      await writeFile(full, body, { flag: 'wx' });
      return { key, url: `${env.API_PUBLIC_URL.replace(/\/$/, '')}/v1/uploads/${key}`, driver: 'disk' };
    },
    async remove(key: string) {
      await rm(pathOf(key), { force: true });
    },
    async read(key: string) {
      try {
        return new Uint8Array(await readFile(pathOf(key)));
      } catch {
        return null;
      }
    },
  };
}

function s3Store(env: Env) {
  const bucket = env.S3_BUCKET!;
  // "auto" is what R2 expects; AWS needs a real region.
  const region = env.S3_REGION === 'auto' && !env.S3_ENDPOINT ? 'us-east-1' : env.S3_REGION;
  const client = new AwsClient({ accessKeyId: env.S3_ACCESS_KEY_ID!, secretAccessKey: env.S3_SECRET_ACCESS_KEY!, service: 's3', region });
  const endpoint = (env.S3_ENDPOINT ?? `https://s3.${region}.amazonaws.com`).replace(/\/$/, '');
  const objectUrl = (key: string) => {
    if (env.S3_FORCE_PATH_STYLE) return `${endpoint}/${bucket}/${key}`;
    const url = new URL(endpoint);
    return `${url.protocol}//${bucket}.${url.host}/${key}`;
  };
  const publicUrl = (key: string) => (env.S3_PUBLIC_URL ? `${env.S3_PUBLIC_URL.replace(/\/$/, '')}/${key}` : objectUrl(key));
  return {
    async put(key: string, body: Uint8Array, contentType: string): Promise<StoredFile> {
      const response = await client.fetch(objectUrl(key), {
        method: 'PUT',
        body,
        headers: { 'content-type': contentType, 'cache-control': CACHE, 'content-length': String(body.byteLength) },
      });
      if (!response.ok) throw new Error(`S3 upload failed with ${response.status}: ${(await response.text()).slice(0, 300)}`);
      return { key, url: publicUrl(key), driver: 's3' };
    },
    async remove(key: string) {
      const response = await client.fetch(objectUrl(key), { method: 'DELETE' });
      if (!response.ok && response.status !== 404) throw new Error(`S3 delete failed with ${response.status}`);
    },
  };
}

export function createStorage(env: Env, logger: Logger): Storage {
  const disk = diskStore(env);
  const s3Ready = Boolean(env.S3_BUCKET && env.S3_ACCESS_KEY_ID && env.S3_SECRET_ACCESS_KEY);
  const s3 = env.STORAGE_DRIVER !== 'disk' && s3Ready ? s3Store(env) : null;
  return {
    primary: s3 ? 's3' : 'disk',
    async put(key, body, contentType) {
      if (s3) {
        try {
          return await s3.put(key, body, contentType);
        } catch (error) {
          // Keep the editor working if the bucket is down or misconfigured; the file lands on this server instead.
          logger.warn({ err: error, key }, 'S3 upload failed, saving to disk instead');
        }
      }
      return disk.put(key, body);
    },
    async remove(key, driver) {
      if (driver === 's3') {
        if (!s3) throw new Error('S3 is not configured, so this file can’t be deleted from the bucket');
        await s3.remove(key);
      } else {
        await disk.remove(key);
      }
    },
    readDisk: (key) => disk.read(key),
  };
}
